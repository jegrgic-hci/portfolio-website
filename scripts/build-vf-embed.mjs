// Builds the vraiFrench component styles for the fr-language-tool case study.
//
// The case study shows the real vraiFrench landing-page visuals (hero stage,
// practice loop, feedback, progress, teacher card). Their CSS comes from the
// vraiFrench repo and is rewritten so every rule only applies inside a
// `.vf` wrapper and cannot touch the portfolio:
//   - :root / html / body and the [data-theme] / [data-mode] attributes they
//     carry move onto the wrapper:  <div class="vf" data-theme="atelier" data-mode="light">
//   - every other selector is prefixed with `.vf `
//   - @keyframes names get a `vf-` prefix so they can't override the portfolio's
//
// Usage: node scripts/build-vf-embed.mjs [path-to-Language_tool]
// Output: public/projects/fr-language-tool/vf/vf-embed.css + pa-voice-atom.js

import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const toolDir = process.argv[2] ?? path.resolve(process.cwd(), "../Language_tool");
const staticDir = path.join(toolDir, "static");
const outDir = path.resolve(process.cwd(), "public/projects/fr-language-tool/vf");

const SHEETS = [
  "vk-tokens.css",
  "vk-components.css",
  "vk-theme-light.css",
  "vk-theme-atelier.css",
  "vk-atelier-components.css",
  "vk-chart.css",
];
const FONTS =
  "https://fonts.googleapis.com/css2?family=Geist+Mono:wght@400;500;600;700&family=Hanken+Grotesk:wght@400;500;600;700;800&display=swap";
const WRAP = ".vf";

// The landing page's own <style> block holds the lp-* layout for the visuals.
const landing = fs.readFileSync(path.join(staticDir, "landing.html"), "utf8");
const landingCss = landing.match(/<style>([\s\S]*?)<\/style>/)[1];

const sources = [
  ...SHEETS.map((f) => ({ name: f, css: fs.readFileSync(path.join(staticDir, f), "utf8") })),
  { name: "landing.html <style>", css: landingCss },
];

// Split a selector on top-level descendant/child combinators, keeping them.
function splitCompounds(sel) {
  const parts = [];
  let depth = 0, cur = "";
  for (let i = 0; i < sel.length; i++) {
    const c = sel[i];
    if (c === "(" || c === "[") depth++;
    if (c === ")" || c === "]") depth--;
    if (depth === 0 && /[\s>+~]/.test(c)) {
      if (cur) parts.push(cur);
      cur = "";
      let comb = c;
      while (i + 1 < sel.length && /[\s>+~]/.test(sel[i + 1])) comb += sel[++i];
      parts.push(comb.trim() || " ");
      continue;
    }
    cur += c;
  }
  if (cur) parts.push(cur);
  return parts;
}

// A compound that names the document root (html, body, :root) and/or only
// carries the theme attributes the wrapper stands in for.
const ROOT_TAG = /^(html|body|:root)/;
const THEME_ATTR = /\[data-(theme|mode)[^\]]*\]/g;
function rootCompound(compound) {
  const rest = compound.replace(ROOT_TAG, "").replace(THEME_ATTR, "");
  if (rest !== "" && !/^\.vk-scroll-lock$/.test(rest)) return null;
  if (!ROOT_TAG.test(compound) && !compound.startsWith("[data-")) return null;
  return { attrs: (compound.match(THEME_ATTR) ?? []).join(""), extra: rest };
}

function scopeSelector(sel) {
  sel = sel.trim();
  const parts = splitCompounds(sel);
  let attrs = "", extra = "", i = 0;
  // Fold leading root/theme compounds (joined by descendant combinators) into the wrapper.
  while (i < parts.length) {
    const r = rootCompound(parts[i]);
    if (!r) break;
    attrs += r.attrs;
    extra += r.extra;
    i++;
    if (parts[i] === " ") i++;
    else break;
  }
  const head = WRAP + attrs + extra;
  const tail = parts.slice(i).join("").trim();
  if (i === 0) return `${WRAP} ${sel}`;
  return tail ? `${head} ${tail.replace(/^[>+~]\s*/, (m) => m)}` : head;
}

const keyframeNames = new Set();
const scope = {
  postcssPlugin: "vf-scope",
  Once(root) {
    root.walkAtRules("keyframes", (at) => {
      keyframeNames.add(at.params);
      at.params = `vf-${at.params}`;
    });
    root.walkRules((rule) => {
      if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
      rule.selectors = rule.selectors.map(scopeSelector);
    });
  },
};

const renameAnimations = {
  postcssPlugin: "vf-keyframes",
  Declaration(decl) {
    if (!/^(animation|animation-name)$/.test(decl.prop)) return;
    decl.value = decl.value.replace(/[\w-]+/g, (w) => (keyframeNames.has(w) ? `vf-${w}` : w));
  },
};

let out = `/* Generated by scripts/build-vf-embed.mjs from the vraiFrench repo. Do not edit by hand. */\n@import url("${FONTS}");\n`;
for (const { name, css } of sources) {
  const scoped = postcss([scope]).process(css, { from: undefined }).css;
  out += `\n/* ── ${name} ── */\n${scoped}\n`;
}
out = postcss([renameAnimations]).process(out, { from: undefined }).css;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "vf-embed.css"), out);
fs.copyFileSync(path.join(staticDir, "pa-voice-atom.js"), path.join(outDir, "pa-voice-atom.js"));
console.log(`vf-embed.css ${(out.length / 1024).toFixed(0)} KB, keyframes renamed: ${[...keyframeNames].join(", ")}`);
